-- ============================================================================
-- NCC Cadet Management Portal - MySQL Database (XAMPP Compatible)
-- 2 Raj Bn NCC: 2nd Year (21), 3rd Year (13) + Separate ANO Logins
-- ============================================================================

CREATE DATABASE IF NOT EXISTS ncc_portal;
USE ncc_portal;

DROP TABLE IF EXISTS achievements;
DROP TABLE IF EXISTS attendance;
DROP TABLE IF EXISTS events;
DROP TABLE IF EXISTS cadets;
DROP TABLE IF EXISTS admins;

-- 1. Admins / ANO Accounts Table (Separate 2 Raj and 10 Raj Logins)
CREATE TABLE admins (
    id INT AUTO_INCREMENT PRIMARY KEY,
    username VARCHAR(50) NOT NULL UNIQUE,
    full_name VARCHAR(100) NOT NULL,
    battalion VARCHAR(20) NOT NULL DEFAULT '2 Raj',
    password_hash VARCHAR(255) NOT NULL
);

-- 2. Cadets Table
CREATE TABLE cadets (
    id INT AUTO_INCREMENT PRIMARY KEY,
    regimental_no VARCHAR(30) NOT NULL UNIQUE,
    full_name VARCHAR(100) NOT NULL,
    rank_title VARCHAR(40) NOT NULL DEFAULT 'Cadet',
    wing VARCHAR(20) NOT NULL DEFAULT '2 Raj',
    unit_name VARCHAR(100) NOT NULL DEFAULT '2 Raj Bn NCC',
    college_branch VARCHAR(80) NOT NULL DEFAULT 'Batch 2025-26',
    year_of_study VARCHAR(20) NOT NULL DEFAULT '2nd Year',
    phone VARCHAR(15) NOT NULL DEFAULT '',
    email VARCHAR(120) NOT NULL DEFAULT '',
    blood_group VARCHAR(10) NOT NULL DEFAULT '',
    enrollment_date DATE NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'Active'
);

-- 3. Attendance Table
CREATE TABLE attendance (
    id INT AUTO_INCREMENT PRIMARY KEY,
    cadet_id INT NOT NULL,
    attendance_date DATE NOT NULL,
    parade_topic VARCHAR(150) NOT NULL,
    status VARCHAR(20) NOT NULL,
    remarks VARCHAR(200) DEFAULT '',
    UNIQUE KEY unique_cadet_date (cadet_id, attendance_date),
    FOREIGN KEY (cadet_id) REFERENCES cadets(id) ON DELETE CASCADE
);

-- 4. Camps & Events Table
CREATE TABLE events (
    id INT AUTO_INCREMENT PRIMARY KEY,
    title VARCHAR(150) NOT NULL,
    event_type VARCHAR(40) NOT NULL,
    event_date DATE NOT NULL,
    location VARCHAR(150) NOT NULL,
    organizer VARCHAR(120) NOT NULL,
    wing VARCHAR(20) NOT NULL DEFAULT '2 Raj',
    description TEXT NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'Upcoming'
);

-- 5. Achievements Table
CREATE TABLE achievements (
    id INT AUTO_INCREMENT PRIMARY KEY,
    cadet_id INT NOT NULL,
    title VARCHAR(160) NOT NULL,
    category VARCHAR(40) NOT NULL,
    level VARCHAR(40) NOT NULL,
    achieved_date DATE NOT NULL,
    remarks VARCHAR(255) DEFAULT '',
    FOREIGN KEY (cadet_id) REFERENCES cadets(id) ON DELETE CASCADE
);

